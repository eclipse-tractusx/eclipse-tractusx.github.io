/**
 * Validates KIT documentation structure against TRG 10-02.
 *
 * Fails when a KIT page is unreachable from its sidebar, when a sidebar entry
 * points at a missing file, or when a KIT uses a non-canonical folder layout.
 * See https://eclipse-tractusx.github.io/docs/release/trg-10/trg-10-02
 */

const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..');
const VERSIONS = ['26.09', '26.06', '26.03', '25.12'];
const VIEWS = ['adoption-view', 'development-view', 'operations-view'];

// Legacy folder names replaced by the canonical ones above.
const FORBIDDEN_DIRS = {
  'software-development-view': 'development-view',
  'software-operation-view': 'operations-view',
  'operation-view': 'operations-view',
  assets: 'resources',
  res: 'resources',
  images: 'resources',
};

const ROOTS = [
  { docs: 'docs-kits', sidebar: 'sidebarsDocsKits.js', label: 'current' },
  ...VERSIONS.map((v) => ({
    docs: `docs-kits_versioned_docs/version-${v}`,
    sidebar: `docs-kits_versioned_sidebars/version-${v}-sidebars.json`,
    label: v,
  })),
];

function collectSidebar(sidebarPath) {
  const abs = path.join(REPO, sidebarPath);
  const raw = sidebarPath.endsWith('.json')
    ? JSON.parse(fs.readFileSync(abs, 'utf8'))
    : require(abs);
  const ids = new Set();
  const autoDirs = [];

  const walk = (node) => {
    if (Array.isArray(node)) return node.forEach(walk);
    if (typeof node === 'string') return ids.add(node);
    if (!node || typeof node !== 'object') return;
    if (node.type === 'autogenerated') return autoDirs.push(node.dirName.replace(/\/$/, ''));
    if (typeof node.id === 'string') ids.add(node.id);
    if (node.items) walk(node.items);
    if (node.link) walk(node.link);
  };
  Object.values(raw).forEach(walk);
  return { ids, autoDirs };
}

function readDocId(file, relDir, basename) {
  // Docusaurus doc id = folder path + (frontmatter `id` || filename)
  const text = fs.readFileSync(file, 'utf8');
  let name = basename;
  const fm = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (fm) {
    const id = fm[1].match(/^id:\s*["']?([^"'\r\n]+?)["']?\s*$/m);
    if (id) name = id[1].trim();
  }
  return relDir ? `${relDir}/${name}` : name;
}

function listDocs(docsRoot) {
  const abs = path.join(REPO, docsRoot, 'kits');
  const out = [];
  if (!fs.existsSync(abs)) return out;
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.mdx?$/.test(entry.name)) {
        const relDir = path
          .relative(path.join(REPO, docsRoot), dir)
          .replace(/\\/g, '/');
        out.push(readDocId(full, relDir, entry.name.replace(/\.mdx?$/, '')));
      }
    }
  };
  walk(abs);
  return out;
}

function checkLayout(docsRoot) {
  const problems = [];
  const warnings = [];
  const kitsDir = path.join(REPO, docsRoot, 'kits');
  if (!fs.existsSync(kitsDir)) return { problems, warnings };

  for (const kit of fs.readdirSync(kitsDir)) {
    const kitPath = path.join(kitsDir, kit);
    if (!fs.statSync(kitPath).isDirectory()) continue;

    for (const entry of fs.readdirSync(kitPath, { withFileTypes: true })) {
      if (entry.isDirectory() && FORBIDDEN_DIRS[entry.name]) {
        problems.push(
          `${docsRoot}/kits/${kit}: folder "${entry.name}/" must be "${FORBIDDEN_DIRS[entry.name]}/"`
        );
      }
      if (entry.isFile() && /\.mdx?$/.test(entry.name)) {
        const stem = entry.name.replace(/\.mdx?$/, '');
        if (VIEWS.includes(stem) || FORBIDDEN_DIRS[stem]) {
          const view = VIEWS.includes(stem) ? stem : FORBIDDEN_DIRS[stem];
          problems.push(
            `${docsRoot}/kits/${kit}: "${entry.name}" must live in "${view}/${view}.md"`
          );
        }
      }
    }

    for (const view of VIEWS) {
      const viewDir = path.join(kitPath, view);
      if (!fs.existsSync(viewDir)) continue;
      const files = fs.readdirSync(viewDir).filter((f) => /\.mdx?$/.test(f));
      if (files.length && !files.some((f) => f.replace(/\.mdx?$/, '') === view)) {
        warnings.push(
          `${docsRoot}/kits/${kit}/${view}: missing main file "${view}.md" (TRG 10-02)`
        );
      }
    }
  }
  return { problems, warnings };
}

function main() {
  const strict = process.argv.includes('--strict');
  const verbose = process.argv.includes('--verbose');
  let failed = false;
  let totalWarnings = 0;

  for (const root of ROOTS) {
    const { ids, autoDirs } = collectSidebar(root.sidebar);
    const docs = listDocs(root.docs).filter((d) => !d.startsWith('kit-template/'));
    const covered = (d) => ids.has(d) || autoDirs.some((a) => d.startsWith(`${a}/`));

    const orphans = docs.filter((d) => !covered(d));
    const docSet = new Set(docs);
    const missing = [...ids].filter((id) => id.startsWith('kits/') && !docSet.has(id));
    const { problems: layoutErrors, warnings: layoutWarnings } = checkLayout(root.docs);

    // Errors break navigation; warnings need a KIT owner's editorial decision.
    const errors = [
      ...missing.map((m) => `[broken sidebar] references missing doc ${m}`),
      ...layoutErrors.map((l) => `[layout] ${l}`),
    ];
    const warnings = [
      ...orphans.map((o) => `[unreachable] ${o} is in no sidebar`),
      ...layoutWarnings.map((l) => `[layout] ${l}`),
    ];

    if (errors.length) {
      failed = true;
      console.error(`\n❌ ${root.label}: ${errors.length} error(s)`);
      errors.forEach((e) => console.error(`   ${e}`));
    } else {
      console.log(`✅ ${root.label}: ${docs.length} KIT docs, structure OK`);
    }

    if (warnings.length) {
      totalWarnings += warnings.length;
      console.warn(`   ⚠️  ${root.label}: ${warnings.length} warning(s)`);
      if (verbose) warnings.forEach((w) => console.warn(`      ${w}`));
    }
  }

  if (totalWarnings) {
    console.warn(
      `\n⚠️  ${totalWarnings} warning(s) total.` +
        (verbose ? '' : ' Run with --verbose to list them.') +
        (strict ? '' : ' Use --strict to treat them as errors.')
    );
    if (strict) failed = true;
  }

  if (failed) {
    console.error('\nKIT structure validation failed — see TRG 10-02.');
    process.exit(1);
  }
  console.log('\nAll KIT structures valid.');
}

main();
